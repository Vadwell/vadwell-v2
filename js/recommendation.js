document.addEventListener("DOMContentLoaded", function () {

    const data = JSON.parse(localStorage.getItem("vadwellResult"));

    if (!data) {
        return;
    }

    let title = "";
    let text = "";

    // Определяем самую слабую категорию
    let categories = {
        "Энергия": data.energy,
        "Восстановление": data.recovery,
        "Активность": data.activity,
        "Привычки": data.habits,
        "Забота о себе": data.selfCare
    };

    let lowestCategory = Object.keys(categories).reduce(function (a, b) {
        return categories[a] < categories[b] ? a : b;
    });

    // Подбираем рекомендацию
    switch (lowestCategory) {

        case "Энергия":
            title = "Ваш профиль: Восстановление энергии";
            text = "Ваш организм может нуждаться в дополнительном восстановлении. Процедура «Лёгкие ноги» поможет расслабиться после насыщенного дня и станет хорошим первым шагом к заботе о себе.";
            break;

        case "Восстановление":
            title = "Ваш профиль: Организму нужен отдых";
            text = "По вашим ответам видно, что организму может быть полезно больше внимания к восстановлению. Процедура «Лёгкие ноги» поможет снять напряжение и уделить время себе.";
            break;

        case "Активность":
            title = "Ваш профиль: Ноги под нагрузкой";
            text = "Если вы много стоите, ходите или проводите день на ногах, процедура «Лёгкие ноги» поможет уменьшить ощущение усталости и подарит чувство лёгкости.";
            break;

        case "Привычки":
            title = "Ваш профиль: Формирование полезных привычек";
            text = "Регулярная забота о себе складывается из небольших ежедневных действий. Процедура «Лёгкие ноги» может стать одной из таких полезных привычек.";
            break;

        case "Забота о себе":
            title = "Ваш профиль: Время уделить внимание себе";
            text = "Даже при высокой занятости важно находить время для восстановления. Процедура «Лёгкие ноги» поможет сделать заботу о себе частью вашей повседневной жизни.";
            break;

        default:
            title = "Ваш профиль VadWell";
            text = "Продолжайте заботиться о своём самочувствии и поддерживать здоровые привычки.";
    }

    document.getElementById("legsRecommendationTitle").innerHTML = title;
    document.getElementById("legsRecommendationText").innerHTML = text;

});
